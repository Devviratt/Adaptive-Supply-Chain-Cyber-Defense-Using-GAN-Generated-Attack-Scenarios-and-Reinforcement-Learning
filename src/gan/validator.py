"""
ASCCD Synthetic Data Validator — statistical fidelity, correlation, and diversity checks.

Evaluates synthetic network attack data generated by CTGAN against real training data.
Calculates Earth Mover's (Wasserstein) Distance, Jensen-Shannon (JS) Divergence,
Pearson correlation preservation, exact and near-duplicate ratios, and mode collapse indicators.

Author: Deekshay G (primary), reviewed by Anandavarthan & Dev Virat
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
import scipy.spatial.distance as dist
import scipy.stats as stats
import yaml

from src.common.logging import get_logger

logger = get_logger(__name__)


@dataclass
class ValidationThresholds:
    """Acceptance criteria thresholds for synthetic dataset validation."""

    max_mean_wasserstein: float = 0.35  # on min-max normalized features
    max_mean_js_divergence: float = 0.45  # Jensen-Shannon divergence [0, 1]
    min_correlation_similarity: float = 0.65  # 1 - (MAE(corr)/2)
    max_duplicate_ratio: float = 0.05  # max 5% exact duplicates
    max_memorization_ratio: float = 0.02  # max 2% identical to real training rows
    range_compliance_threshold: float = 0.90  # % of values within real range +/- 3 std
    max_mode_collapsed_features: int = 5  # max features with zero or near-zero variance


@dataclass
class ValidationSummary:
    """Structured report of synthetic data quality assessment."""

    total_real_samples: int = 0
    total_synthetic_samples: int = 0
    num_features: int = 0
    schema_passed: bool = False
    no_nan_or_inf_passed: bool = False
    valid_labels_passed: bool = False
    mean_wasserstein_distance: float = 0.0
    median_wasserstein_distance: float = 0.0
    mean_js_divergence: float = 0.0
    median_js_divergence: float = 0.0
    correlation_similarity: float = 0.0
    correlation_frobenius_norm: float = 0.0
    synthetic_duplicate_ratio: float = 0.0
    memorized_samples_ratio: float = 0.0
    mode_collapsed_features: list[str] = field(default_factory=list)
    per_feature_wasserstein: dict[str, float] = field(default_factory=dict)
    per_feature_js_divergence: dict[str, float] = field(default_factory=dict)
    real_class_distribution: dict[str, int] = field(default_factory=dict)
    synthetic_class_distribution: dict[str, int] = field(default_factory=dict)
    passed_all_criteria: bool = False
    validation_status: str = "PENDING"  # PASSED, WARNING, FAILED
    failure_reasons: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """Convert summary to dictionary."""
        return asdict(self)


class SyntheticDataValidator:
    """Comprehensive validator for synthetic attack scenarios."""

    def __init__(
        self,
        config: dict[str, Any] | None = None,
        config_path: str | Path | None = None,
        thresholds: ValidationThresholds | None = None,
    ) -> None:
        self.config = self._load_config(config, config_path)
        self.thresholds = thresholds or self._parse_thresholds()

    def _load_config(
        self, config: dict[str, Any] | None, config_path: str | Path | None
    ) -> dict[str, Any]:
        if config is not None:
            return config
        path = config_path or Path("config/gan.yaml")
        if Path(path).exists():
            with open(path) as f:
                return yaml.safe_load(f) or {}
        return {}

    def _parse_thresholds(self) -> ValidationThresholds:
        val_cfg = self.config.get("ctgan", {}).get("validation", {})
        return ValidationThresholds(
            max_mean_wasserstein=val_cfg.get("max_mean_wasserstein", 0.35),
            max_mean_js_divergence=val_cfg.get("max_kl_divergence", 0.50),
            min_correlation_similarity=val_cfg.get("min_correlation_similarity", 0.65),
            max_duplicate_ratio=val_cfg.get("max_duplicate_ratio", 0.05),
            range_compliance_threshold=val_cfg.get("range_compliance_threshold", 0.90),
        )

    def validate(
        self,
        real_df: pd.DataFrame,
        synthetic_df: pd.DataFrame,
    ) -> ValidationSummary:
        """Run complete statistical and schema validation of synthetic dataset against real data.

        Strict Evaluation Steps:
          1. Schema and Column Order Conformance
          2. Non-finite (NaN / Inf) Isolation
          3. Label Domain Validity
          4. 1-D Marginal Fidelity (Wasserstein Distance & Jensen-Shannon Divergence)
          5. 2-D Dependency Structure (Pearson Correlation Similarity)
          6. Diversity & Mode Collapse Assessment (Exact Duplicates & Variance Check)

        Args:
            real_df: Real training DataFrame (e.g. data/processed/train.csv).
            synthetic_df: Synthetic DataFrame generated by CTGAN.

        Returns:
            ValidationSummary detailing metrics and pass/fail status.
        """
        logger.info(
            "starting_synthetic_data_validation",
            real_rows=len(real_df),
            synthetic_rows=len(synthetic_df),
        )

        failures: list[str] = []

        # 1. Non-empty check
        if real_df.empty or synthetic_df.empty:
            return ValidationSummary(
                passed_all_criteria=False,
                validation_status="FAILED",
                failure_reasons=["One or both datasets are empty."],
            )

        # 2. Schema conformity check
        schema_passed = True
        if list(real_df.columns) != list(synthetic_df.columns):
            missing_in_synth = set(real_df.columns) - set(synthetic_df.columns)
            extra_in_synth = set(synthetic_df.columns) - set(real_df.columns)
            order_mismatch = set(real_df.columns) == set(synthetic_df.columns) and list(
                real_df.columns
            ) != list(synthetic_df.columns)

            if missing_in_synth:
                failures.append(f"Synthetic data is missing columns: {list(missing_in_synth)[:5]}")
                schema_passed = False
            if extra_in_synth:
                failures.append(
                    f"Synthetic data has unexpected columns: {list(extra_in_synth)[:5]}"
                )
                schema_passed = False
            if order_mismatch:
                failures.append("Column order in synthetic data does not match real data.")
                schema_passed = False

        # 3. Non-finite values check
        has_nan = bool(synthetic_df.isnull().any().any())
        numeric_cols = [
            c
            for c in real_df.select_dtypes(include=[np.number]).columns
            if c in synthetic_df.columns
        ]
        has_inf = False
        if numeric_cols:
            vals = synthetic_df[numeric_cols].to_numpy(dtype=float, na_value=0.0)
            has_inf = bool(np.isinf(vals).any())

        no_nan_or_inf = not (has_nan or has_inf)
        if not no_nan_or_inf:
            failures.append(
                f"Synthetic data contains non-finite values (NaN: {has_nan}, Inf: {has_inf})."
            )

        # 4. Label validity check
        valid_labels_passed = True
        real_labels = set(real_df["Label"].unique()) if "Label" in real_df.columns else set()
        synth_labels = (
            set(synthetic_df["Label"].unique()) if "Label" in synthetic_df.columns else set()
        )

        if "Label" in real_df.columns and "Label" in synthetic_df.columns:
            invented_labels = synth_labels - real_labels
            if invented_labels:
                failures.append(
                    f"Synthetic data invented labels not seen in training: {invented_labels}"
                )
                valid_labels_passed = False

        real_class_dist = (
            {str(k): int(v) for k, v in real_df["Label"].value_counts().items()}
            if "Label" in real_df.columns
            else {}
        )
        synth_class_dist = (
            {str(k): int(v) for k, v in synthetic_df["Label"].value_counts().items()}
            if "Label" in synthetic_df.columns
            else {}
        )

        # 5. Marginal Statistical Distance (Wasserstein & Jensen-Shannon)
        per_feat_wasserstein: dict[str, float] = {}
        per_feat_js: dict[str, float] = {}
        mode_collapsed: list[str] = []

        for col in numeric_cols:
            real_series = real_df[col].dropna()
            synth_series = synthetic_df[col].dropna()

            if len(real_series) == 0 or len(synth_series) == 0:
                continue

            r_std = float(real_series.std())
            s_std = float(synth_series.std())

            # Mode collapse check (zero or extremely tiny variance in synthetic when real has variance)
            if r_std > 1e-4 and s_std < 1e-6:
                mode_collapsed.append(col)

            # Min-Max Normalization based on real feature range for scale-invariant Wasserstein
            r_min, r_max = float(real_series.min()), float(real_series.max())
            denom = r_max - r_min if (r_max - r_min) > 1e-6 else 1.0

            r_norm = (real_series - r_min) / denom
            s_norm = (synth_series - r_min) / denom

            # Wasserstein Distance
            w_dist = float(stats.wasserstein_distance(r_norm, s_norm))
            per_feat_wasserstein[col] = round(w_dist, 4)

            # Jensen-Shannon Divergence via Empirical Histograms
            # Use combined range to define 20 bins
            combined_min = min(r_min, float(synth_series.min()))
            combined_max = max(r_max, float(synth_series.max()))
            if combined_max - combined_min > 1e-6:
                bins = np.linspace(combined_min, combined_max, 21)
                hist_r, _ = np.histogram(real_series, bins=bins)
                hist_s, _ = np.histogram(synth_series, bins=bins)

                # Add laplace smoothing to avoid zero probabilities
                p = (hist_r + 1e-5) / (np.sum(hist_r) + 1e-5 * len(hist_r))
                q = (hist_s + 1e-5) / (np.sum(hist_s) + 1e-5 * len(hist_s))

                js_div = float(dist.jensenshannon(p, q, base=2))
            else:
                js_div = 0.0

            per_feat_js[col] = round(js_div, 4)

        mean_w = (
            float(np.mean(list(per_feat_wasserstein.values()))) if per_feat_wasserstein else 0.0
        )
        med_w = (
            float(np.median(list(per_feat_wasserstein.values()))) if per_feat_wasserstein else 0.0
        )
        mean_js = float(np.mean(list(per_feat_js.values()))) if per_feat_js else 0.0
        med_js = float(np.median(list(per_feat_js.values()))) if per_feat_js else 0.0

        if mean_w > self.thresholds.max_mean_wasserstein:
            failures.append(
                f"Mean Wasserstein distance ({mean_w:.3f}) exceeded threshold "
                f"({self.thresholds.max_mean_wasserstein:.3f})."
            )

        if mean_js > self.thresholds.max_mean_js_divergence:
            failures.append(
                f"Mean Jensen-Shannon divergence ({mean_js:.3f}) exceeded threshold "
                f"({self.thresholds.max_mean_js_divergence:.3f})."
            )

        # 6. Correlation Matrix Structure Preservation
        real_corr = real_df[numeric_cols].corr().fillna(0.0).values
        synth_corr = synthetic_df[numeric_cols].corr().fillna(0.0).values

        corr_diff = np.abs(real_corr - synth_corr)
        mae_corr = float(np.nanmean(corr_diff))
        corr_sim = max(0.0, 1.0 - (mae_corr / 2.0))

        real_frobenius = float(np.linalg.norm(real_corr))
        frobenius_norm_diff = (
            float(np.linalg.norm(corr_diff)) / real_frobenius if real_frobenius > 1e-6 else 0.0
        )

        if corr_sim < self.thresholds.min_correlation_similarity:
            failures.append(
                f"Correlation similarity score ({corr_sim:.3f}) fell below threshold "
                f"({self.thresholds.min_correlation_similarity:.3f})."
            )

        # 7. Diversity and Duplicate Checks
        num_synth = len(synthetic_df)
        dup_count = int(synthetic_df.duplicated().sum())
        synth_dup_ratio = dup_count / num_synth if num_synth > 0 else 0.0

        if synth_dup_ratio > self.thresholds.max_duplicate_ratio:
            failures.append(
                f"Synthetic duplicate ratio ({synth_dup_ratio:.3%}) exceeded maximum "
                f"({self.thresholds.max_duplicate_ratio:.3%})."
            )

        # Memorization check (exact matches between synthetic and real)
        # Check on a hash of values to be fast and memory-efficient
        real_tuples = set(map(tuple, real_df[numeric_cols].iloc[:1000].round(4).to_numpy()))
        synth_tuples = list(map(tuple, synthetic_df[numeric_cols].iloc[:1000].round(4).to_numpy()))
        memorized_count = sum(1 for st in synth_tuples if st in real_tuples)
        memorized_ratio = memorized_count / len(synth_tuples) if synth_tuples else 0.0

        if memorized_ratio > self.thresholds.max_memorization_ratio:
            failures.append(
                f"Memorization ratio ({memorized_ratio:.3%}) exceeded maximum threshold "
                f"({self.thresholds.max_memorization_ratio:.3%}). CTGAN may be copying training rows."
            )

        if len(mode_collapsed) > self.thresholds.max_mode_collapsed_features:
            failures.append(
                f"Detected {len(mode_collapsed)} mode-collapsed features (threshold: {self.thresholds.max_mode_collapsed_features})."
            )

        # Overall Status
        passed_all = len(failures) == 0
        status = "PASSED" if passed_all else ("WARNING" if len(failures) <= 1 else "FAILED")

        summary = ValidationSummary(
            total_real_samples=len(real_df),
            total_synthetic_samples=len(synthetic_df),
            num_features=len(synthetic_df.columns),
            schema_passed=schema_passed,
            no_nan_or_inf_passed=no_nan_or_inf,
            valid_labels_passed=valid_labels_passed,
            mean_wasserstein_distance=round(mean_w, 4),
            median_wasserstein_distance=round(med_w, 4),
            mean_js_divergence=round(mean_js, 4),
            median_js_divergence=round(med_js, 4),
            correlation_similarity=round(corr_sim, 4),
            correlation_frobenius_norm=round(frobenius_norm_diff, 4),
            synthetic_duplicate_ratio=round(synth_dup_ratio, 4),
            memorized_samples_ratio=round(memorized_ratio, 4),
            mode_collapsed_features=mode_collapsed,
            per_feature_wasserstein=per_feat_wasserstein,
            per_feature_js_divergence=per_feat_js,
            real_class_distribution=real_class_dist,
            synthetic_class_distribution=synth_class_dist,
            passed_all_criteria=passed_all,
            validation_status=status,
            failure_reasons=failures,
        )

        logger.info(
            "synthetic_validation_finished",
            status=status,
            mean_wasserstein=round(mean_w, 4),
            mean_js=round(mean_js, 4),
            correlation_similarity=round(corr_sim, 4),
            duplicate_ratio=round(synth_dup_ratio, 4),
            passed_all=passed_all,
        )

        return summary

    def export_reports(
        self,
        summary: ValidationSummary,
        output_dir: str | Path = "artifacts/reports",
        filename_prefix: str = "synthetic_data_validation",
    ) -> tuple[Path, Path]:
        """Export validation findings to JSON and Markdown reports."""
        out_dir = Path(output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)

        json_path = out_dir / f"{filename_prefix}.json"
        md_path = out_dir / f"{filename_prefix}.md"

        # JSON Export
        with open(json_path, "w") as f:
            json.dump(summary.to_dict(), f, indent=2, default=str)

        # Markdown Export
        md_content = self._render_markdown_report(summary)
        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        logger.info("synthetic_reports_exported", json=str(json_path), md=str(md_path))
        return json_path, md_path

    def _render_markdown_report(self, summary: ValidationSummary) -> str:
        """Render detailed Markdown report."""
        status_badge = (
            "✅ PASSED" if summary.passed_all_criteria else f"⚠️ {summary.validation_status}"
        )
        lines = [
            "# Synthetic Attack Data Quality & Fidelity Report",
            "",
            f"**Validation Status:** {status_badge}  ",
            f"**Total Real Samples:** {summary.total_real_samples:,}  ",
            f"**Total Synthetic Samples:** {summary.total_synthetic_samples:,}  ",
            f"**Total Evaluated Features:** {summary.num_features}  ",
            "",
            "---",
            "",
            "## 1. Key Evaluation Metrics",
            "",
            "| Metric | Value | Acceptance Threshold | Result |",
            "| :--- | :--- | :--- | :--- |",
            f"| **Mean Wasserstein Distance (W1)** | `{summary.mean_wasserstein_distance:.4f}` | `< {self.thresholds.max_mean_wasserstein:.2f}` | {'✅ PASS' if summary.mean_wasserstein_distance <= self.thresholds.max_mean_wasserstein else '❌ FAIL'} |",
            f"| **Median Wasserstein Distance** | `{summary.median_wasserstein_distance:.4f}` | Reference | - |",
            f"| **Mean Jensen-Shannon Divergence** | `{summary.mean_js_divergence:.4f}` | `< {self.thresholds.max_mean_js_divergence:.2f}` | {'✅ PASS' if summary.mean_js_divergence <= self.thresholds.max_mean_js_divergence else '❌ FAIL'} |",
            f"| **Pearson Correlation Similarity** | `{summary.correlation_similarity:.4f}` | `> {self.thresholds.min_correlation_similarity:.2f}` | {'✅ PASS' if summary.correlation_similarity >= self.thresholds.min_correlation_similarity else '❌ FAIL'} |",
            f"| **Relative Frobenius Norm Diff** | `{summary.correlation_frobenius_norm:.4f}` | Reference | - |",
            f"| **Synthetic Exact Duplicate Ratio** | `{summary.synthetic_duplicate_ratio:.2%}` | `< {self.thresholds.max_duplicate_ratio:.1%}` | {'✅ PASS' if summary.synthetic_duplicate_ratio <= self.thresholds.max_duplicate_ratio else '❌ FAIL'} |",
            f"| **Real-to-Synthetic Memorization** | `{summary.memorized_samples_ratio:.2%}` | `< {self.thresholds.max_memorization_ratio:.1%}` | {'✅ PASS' if summary.memorized_samples_ratio <= self.thresholds.max_memorization_ratio else '❌ FAIL'} |",
            f"| **Mode Collapsed Features** | `{len(summary.mode_collapsed_features)}` | `< {self.thresholds.max_mode_collapsed_features}` | {'✅ PASS' if len(summary.mode_collapsed_features) <= self.thresholds.max_mode_collapsed_features else '❌ FAIL'} |",
            "",
            "---",
            "",
            "## 2. Integrity and Schema Checks",
            "",
            f"- Schema & Column Order Match: `{'PASS' if summary.schema_passed else 'FAIL'}`",
            f"- Zero NaN / Inf Values: `{'PASS' if summary.no_nan_or_inf_passed else 'FAIL'}`",
            f"- Valid Label Set (No Hallucinated Classes): `{'PASS' if summary.valid_labels_passed else 'FAIL'}`",
            "",
            "## 3. Class Distribution Comparison",
            "",
            "| Class Label | Real Training Count | Synthetic Count | Synthetic Proportion |",
            "| :--- | :--- | :--- | :--- |",
        ]

        all_classes = sorted(
            set(summary.real_class_distribution.keys())
            | set(summary.synthetic_class_distribution.keys())
        )
        synth_total = max(1, summary.total_synthetic_samples)
        for cls_name in all_classes:
            r_cnt = summary.real_class_distribution.get(cls_name, 0)
            s_cnt = summary.synthetic_class_distribution.get(cls_name, 0)
            lines.append(f"| `{cls_name}` | {r_cnt:,} | {s_cnt:,} | {s_cnt / synth_total:.2%} |")

        if summary.failure_reasons:
            lines.extend(
                [
                    "",
                    "---",
                    "",
                    "## 4. Warnings and Failures",
                    "",
                ]
            )
            for reason in summary.failure_reasons:
                lines.append(f"- ⚠️ {reason}")

        return "\n".join(lines) + "\n"
